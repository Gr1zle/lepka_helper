"""Информация о версии и понятное описание работы с данными."""
import flet as ft
from app_info import APP_TITLE, APP_VERSION


def showDataInfo(page):
    dialog = ft.AlertDialog(title=ft.Text('Условия использования и данные'),
        content=ft.Column(width=340, height=330, scroll=ft.ScrollMode.AUTO, controls=[
            ft.Text('Это учебное приложение для ведения проектов по лепке.'),
            ft.Text('Для аккаунта сохраняются email, хеш пароля, профиль и настройки. '
                    'Регистрация подтверждается кодом на почту. Для проверки есть отдельный тестовый аккаунт.'),
            ft.Text('В локальном режиме данные находятся на устройстве. При подключённом API аккаунты, '
                    'публикации и прогресс мастер-классов находятся на сервере; личные проекты, палитра, '
                    'встроенный прогресс, избранные уроки и модели, заметки и история поиска — на устройстве.'),
            ft.Text('Опубликованные фото, описание, выбранные этапы и рецепты видны другим пользователям сообщества. '
                    'Публикуйте изображения, которыми готовы поделиться.'),
            ft.Text('Свою публикацию можно удалить. При удалении аккаунта чужие комментарии остаются под заглушкой '
                    '«Работа удалена пользователем». Ранее скопированные другими людьми рецепты остаются у них.')]),
        actions=[ft.TextButton('Понятно', on_click=lambda event: page.close(dialog))])
    page.open(dialog)


